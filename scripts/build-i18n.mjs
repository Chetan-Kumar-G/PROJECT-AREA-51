// Builds site/js/i18n/<lang>.js from the translation files in i18n/<lang>/*.json,
// and checks that every machine and every key used by the pages is translated.
// Run from the repo root:  node scripts/build-i18n.mjs
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sandbox = {};
vm.runInNewContext(readFileSync(join(root, "site/js/data.js"), "utf8") + ";globalThis.__a = ARTIFACTS;", sandbox);
const ARTIFACTS = sandbox.__a;

// keys the pages ask for
const html = readFileSync(join(root, "site/index.html"), "utf8");
const app = ["app.js", "oppy.js", "story.js", "explainers.js", "pwa.js"].map(f => readFileSync(join(root, "site/js", f), "utf8")).join("\n");
vm.runInNewContext(readFileSync(join(root, "site/js/oppy-data.js"), "utf8") + ";globalThis.__o = OPPY;", sandbox);
const OPPY = sandbox.__o;
const used = new Set([
  ...[...html.matchAll(/data-i(?:-ph|-al)?="([^"]+)"/g)].map(m => m[1]),
  ...[...app.matchAll(/\bt\("([\w.]+)"/g)].map(m => m[1]),
  "page.title", "page.desc"
]);

const merge = (a, b) => {
  for (const [k, v] of Object.entries(b)) a[k] = v && typeof v === "object" && !Array.isArray(v) ? merge(a[k] || {}, v) : v;
  return a;
};
mkdirSync(join(root, "site/js/i18n"), { recursive: true });
let problems = 0;
for (const lang of readdirSync(join(root, "i18n"))) {
  const dir = join(root, "i18n", lang);
  const data = { lang };
  for (const f of readdirSync(dir).filter(f => f.endsWith(".json")).sort()) merge(data, JSON.parse(readFileSync(join(dir, f), "utf8")));
  const missing = [];
  for (const k of used) if (!data.ui || data.ui[k] == null) missing.push("ui:" + k);
  for (const a of ARTIFACTS) {
    const m = (data.m || {})[a.id];
    if (!m) { missing.push("machine:" + a.id); continue; }
    for (const f of ["story", "ghost", "epitaph", "fun"]) if (!m[f]) missing.push(`${a.id}.${f}`);
    if (a.quiz && !m.quiz) missing.push(`${a.id}.quiz`);
  }
  const o = data.oppy || {};
  OPPY.moments.forEach((m, k) => { for (const f of ["date", "title", "text", "memory"]) if (!o.moments?.[k]?.[f]) missing.push(`oppy.moments[${k}].${f}`); });
  OPPY.stops.forEach((s, k) => { if (!o.stops?.[k]) missing.push(`oppy.stops[${k}]`); });
  OPPY.parts.forEach(p => { for (const f of ["name", "text"]) if (!o.parts?.[p.id]?.[f]) missing.push(`oppy.parts.${p.id}.${f}`); });
  if (missing.length) { problems += missing.length; console.log(`${lang}: MISSING ${missing.length}: ${missing.join(", ")}`); }
  writeFileSync(join(root, "site/js/i18n", lang + ".js"),
    `/* GENERATED by scripts/build-i18n.mjs from i18n/${lang}/*.json — edit those files, not this one. */\nwindow.I18N = ${JSON.stringify(data)};\n`);
  console.log(`${lang}: ${Object.keys(data.ui || {}).length} interface strings, ${Object.keys(data.m || {}).length} machines`);
}
if (problems) process.exitCode = 1;
