// Builds site/sw.js (the offline service worker) with the list of files to save.
// Run from the repo root after adding or renaming files:  node scripts/build-sw.mjs
// Pages, scripts and styles are always fetched fresh when online (network first),
// so you only need to re-run this when files are added or removed.
import { readdirSync, statSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "site");

// 1) Cache-busting: stamp every local stylesheet/script link in the pages with a
//    fingerprint of the file's contents (e.g. css/style.css?v=3f9a1c2b). When a file
//    changes, its address changes, so browsers can never mix a new page with an old file.
const fingerprint = rel => createHash("sha1").update(readFileSync(join(root, rel))).digest("hex").slice(0, 8);
let stamped = 0;
const pagesToStamp = readdirSync(root).filter(f => f.endsWith(".html")).map(f => join(root, f));
try { pagesToStamp.push(...readdirSync(join(root, "machines")).filter(f => f.endsWith(".html")).map(f => join(root, "machines", f))); } catch { /* not built yet */ }
for (const p of pagesToStamp) {
  const before = readFileSync(p, "utf8");
  let after = before.replace(/(href|src)="((?:\.\.\/)?)((?:css|js)\/[\w.-]+\.(?:css|js))(?:\?v=[\w]+)?"/g, (m, attr, up, rel) => {
    try { stamped++; return `${attr}="${up}${rel}?v=${fingerprint(rel)}"`; } catch { return m; }
  });
  // language files are loaded by a script string ("js/i18n/es.js"), so stamp those too
  after = after.replace(/"(js\/i18n\/[\w-]+\.js)(?:\?v=\w+)?"/g, (m, rel) => { try { stamped++; return `"${rel}?v=${fingerprint(rel)}"`; } catch { return m; } });
  if (after !== before) writeFileSync(p, after);
}
const SKIP = [/^atlas\//, /^sw\.js$/, /^assets\/models\//, /^assets\/maps\/hd\//, /^machines\//, /^js\/i18n\//, /^sitemap\.xml$/, /^robots\.txt$/]; // hd = optional NASA JPL mode textures // 3D models are large: cached the first time someone opens them
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else {
      const rel = relative(root, p).split("\\").join("/");
      if (!SKIP.some(re => re.test(rel))) files.push(rel);
    }
  }
})(root);
files.sort();
const hash = createHash("sha1");
files.forEach(f => hash.update(f + readFileSync(join(root, f)).length));
const version = hash.digest("hex").slice(0, 10);

const sw = `// GENERATED by scripts/build-sw.mjs — do not edit by hand.
const VERSION = "goe-${version}";
const PRECACHE = ${JSON.stringify(["./", ...files], null, 0)};

self.addEventListener("install", e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== VERSION && k.startsWith("goe-")).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});

const FRESH = /\\.(html|js|css|json|webmanifest)$/;
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  // Never cache video/audio streams (large files with range requests).
  if (/\\.(mp4|mp3|wav|m4a)$/i.test(url.pathname) || req.headers.has("range")) return;
  const same = url.origin === location.origin;
  // The teammate 3D app (atlas/) manages its own large files (the Unity player is ~100 MB): leave it to the network.
  if (same && url.pathname.includes("/atlas/")) return;
  if (same && (req.mode === "navigate" || FRESH.test(url.pathname))) {
    // Network first, so updates show up straight away; fall back to the saved copy offline.
    // cache: "no-cache" makes the browser re-check with the server instead of reusing
    // its short-term copy (GitHub Pages lets browsers reuse files for 10 minutes).
    e.respondWith(fetch(req, { cache: "no-cache" }).then(res => { if (res.ok) caches.open(VERSION).then(c => c.put(req, res.clone())); return res; })
      .catch(() => caches.match(req, { ignoreSearch: true }).then(r => r || caches.match("./index.html"))));
    return;
  }
  // Images, maps, models and CDN libraries/fonts: cache first, then save anything new.
  const cacheable = same || /(fonts\\.googleapis\\.com|fonts\\.gstatic\\.com|cdn\\.jsdelivr\\.net|unpkg\\.com|images-assets\\.nasa\\.gov)$/.test(url.hostname);
  if (!cacheable) return;
  e.respondWith(caches.match(req, { ignoreSearch: same }).then(hit => hit || fetch(req).then(res => {
    if (res.ok || res.type === "opaque") { const copy = res.clone(); caches.open(VERSION).then(c => c.put(req, copy)); }
    return res;
  })));
});
`;
writeFileSync(join(root, "sw.js"), sw);
const bytes = files.reduce((n, f) => n + statSync(join(root, f)).size, 0);
console.log(`Stamped ${stamped} stylesheet/script links with content fingerprints.`);
console.log(`Wrote site/sw.js — ${files.length} files (${(bytes / 1e6).toFixed(1)} MB) saved for offline use, version ${version}`);
