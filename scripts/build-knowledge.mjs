// Turns site/js/data.js into the AI's knowledge file (worker/src/knowledge.js).
// Run from the repo root:  node scripts/build-knowledge.mjs
// Re-run it whenever you edit data.js, then redeploy the worker.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "site/js/data.js"), "utf8");

// data.js declares top-level consts for the browser; expose them from a sandbox.
const sandbox = {};
// records.js (instrument lists from the Cosmic-Atlas catalogue) is optional
let recSrc = "const RECORDS = {};";
try { recSrc = readFileSync(join(root, "site/js/records.js"), "utf8"); } catch { /* not present */ }
vm.runInNewContext(
  src + "\n" + recSrc + "\n;globalThis.__out = { ARTIFACTS, STATUS, TYPES, WORLDS, MODELS, CHAPTERS, ASK_FAQ, RECORDS };",
  sandbox,
);
const { ARTIFACTS, STATUS, TYPES, WORLDS, MODELS } = sandbox.__out;

const line = (k, v) => (v === undefined || v === null || v === "" ? "" : `${k}: ${v}\n`);
const coord = (a) =>
  a.lat == null ? "" : `${Math.abs(a.lat)}°${a.lat >= 0 ? "N" : "S"}, ${Math.abs(a.lon)}°${a.lon >= 0 ? "E" : "W"}`;

let out = "# Ghosts of Exploration — archive\n\n";
out += "## Status meanings\n";
for (const [k, s] of Object.entries(STATUS)) out += `- ${s.label}: ${s.desc}\n`;
out += "\n";

for (const world of ["moon", "mars", "deep"]) {
  out += `## ${WORLDS[world].name}\n\n`;
  for (const a of ARTIFACTS.filter((x) => x.world === world)) {
    out += `### ${a.name}${a.nick ? ` (${a.nick})` : ""} [id: ${a.id}]\n`;
    out += line("Type", TYPES[a.type]);
    out += line("Status", STATUS[a.status].label);
    out += line("Mission", a.mission);
    out += line("Year", a.year);
    out += line("Place", a.place || a.fixedPlace);
    out += line("Coordinates", coord(a));
    out += line("Launched", a.dates.launch);
    out += line("Arrived", a.dates.arrive);
    out += line("Last contact / status", a.dates.last);
    if (a.dist)
      out += line(
        "Distance from the Sun",
        `about ${a.dist.au2025} AU on 1 Jan 2025, moving outward about ${a.dist.rate} AU per year (estimate)`,
      );
    out += line("Heading", a.heading);
    out += line("Planned", a.planned);
    out += line("What happened", a.actual);
    out += line("Numbers", a.stats.filter(([, v]) => v !== "live").map(([k, v]) => `${k}: ${v}`).join("; "));
    out += line("Ghost log (first-person, storytelling voice)", a.ghost);
    out += line("Epitaph (one-line memorial in its own voice, written for this archive)", a.epitaph);
    out += line("Story (ages 8-11)", a.story);
    out += line("Science story (ages 12+)", a.deep);
    out += line("Discoveries", a.discoveries.join("; "));
    if (a.left) out += line("Left behind", a.left.join("; "));
    out += line("Why it matters today", a.legacy);
    out += line("Fun fact", a.fun);
    for (const g of (sandbox.__out.RECORDS[a.id] || {}).onboard || []) {
      out += line(`On board / left behind: ${g.name}`, [g.design, g.status && `Today: ${g.status}`].filter(Boolean).join(" "));
      for (const i of g.items) out += line(`  - ${i.name}`, [i.what, i.found && `Found: ${i.found.join(" ")}`, i.specs && i.specs.join("; ")].filter(Boolean).join(" "));
    }
    if (MODELS[a.id]) out += line("3D model on the site", `${MODELS[a.id].title} — ${MODELS[a.id].note}`);
    out += "\n";
  }
}

out += "## Questions and answers (mostly about Opportunity and the Mars Exploration Rovers)\n\n";
for (const f of sandbox.__out.ASK_FAQ) out += `Q: ${f.q}\nA: ${f.a.replace(/\*\*/g, "")}\n\n`;

const dest = join(root, "worker/src/knowledge.js");
const content =
  "// GENERATED by scripts/build-knowledge.mjs from site/js/data.js — do not edit by hand.\n" +
  `export const KNOWLEDGE = ${JSON.stringify(out)};\n` +
  `export const ARTIFACT_NAMES = ${JSON.stringify(ARTIFACTS.map((a) => ({ id: a.id, name: a.name, nick: a.nick || null })))};\n`;
mkdirSync(dirname(dest), { recursive: true });
// Only write when something changed, so `wrangler dev` (which watches src/) doesn't rebuild forever.
let existing = null;
try { existing = readFileSync(dest, "utf8"); } catch { /* first run */ }
if (existing === content) {
  console.log(`knowledge.js is up to date (${ARTIFACTS.length} artifacts)`);
} else {
  writeFileSync(dest, content);
  console.log(`Wrote ${dest} — ${ARTIFACTS.length} artifacts, ${out.length.toLocaleString()} characters`);
}
